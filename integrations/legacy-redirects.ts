// Appends 301s for pre-Astro URLs to dist/.htaccess:
//   notes/course_notes/<COURSE>/                       -> notes/<course>/
//   tools/md-viewer/?…note=<File>_<lang>.md (or file=) -> notes/<course>/<slug>/<lang>/
//   notes/course_notes/<COURSE>/<File>_<lang>.md        -> notes/<course>/<slug>/<lang>/source.md
// Targets are absolute https URLs: a relative target comes out as http:// behind
// the ICS proxy and browsers block it as mixed content.
import type { AstroIntegration } from "astro";
import { appendFileSync, readFileSync } from "node:fs";

const escapeRe = (s: string) => s.replace(/[.\-]/g, "\\$&");

export default function legacyRedirects(): AstroIntegration {
  let origin = "";
  return {
    name: "legacy-redirects",
    hooks: {
      "astro:config:done": ({ config }) => {
        origin = new URL(config.base.replace(/\/?$/, "/"), config.site).href;
      },
      "astro:build:done": ({ dir }) => {
        const map: Record<string, string> = JSON.parse(readFileSync("src/data/legacy-notes.json", "utf8"));
        const courses = [...new Set(Object.keys(map).map((k) => k.split("/")[0]!))];
        const lines = ["", "# ── Legacy URLs (generated by integrations/legacy-redirects.ts) ──"];
        for (const course of courses) {
          lines.push(`RewriteRule ^notes/course_notes/${escapeRe(course)}(/(index\\.html)?)?$ ${origin}notes/${course.toLowerCase()}/ [R=301,L]`);
        }
        lines.push(`RewriteRule ^notes/course_notes/?$ ${origin}notes/ [R=301,L]`);
        for (const [legacy, id] of Object.entries(map)) {
          const file = legacy.split("/")[1]!;
          const m = /^([^/]+)\/([^.]+)\.(.+)$/.exec(id)!;
          lines.push(`RewriteCond %{QUERY_STRING} (^|[&=/]|%2F)${escapeRe(file)}(&|$) [NC]`);
          const target = `${origin}notes/${m[1]!.toLowerCase()}/${m[2]}/${m[3]}/`;
          lines.push(`RewriteRule ^tools/md-viewer/?(index\\.html)?$ ${target}? [R=301,L]`);
          lines.push(`RewriteRule ^notes/course_notes/${escapeRe(legacy)}$ ${target}source.md [R=301,L]`);
        }
        appendFileSync(new URL(".htaccess", dir), lines.join("\n") + "\n");
      },
    },
  };
}
